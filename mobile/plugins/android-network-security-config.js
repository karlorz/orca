const fs = require('fs')
const path = require('path')
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins')

// Fixed dev hosts that network_security_config CAN name: loopback and the Android emulator's alias
// for the host machine.
const CLEARTEXT_DEV_DOMAINS = ['localhost', '127.0.0.1', '10.0.2.2']

// Tailscale MagicDNS (*.ts.net). The tunnel is WireGuard-encrypted, so ws:// inside it is safe.
// Tailscale IPs (100.64.0.0/10) are a range and cannot be listed here; the JS policy covers them.
const CLEARTEXT_SUBDOMAIN_DOMAINS = ['ts.net']

// LIMITATION, stated plainly: network_security_config grants cleartext per DOMAIN (<domain>), not
// per IP range. "Cleartext only to RFC1918 (10/8, 172.16/12, 192.168/16) and link-local
// (169.254/16)" cannot be expressed in this file, and pairing a phone with a desktop on the LAN is
// plain ws:// to exactly such an address. So <base-config> must keep cleartext permitted, or every
// LAN pairing breaks (once networkSecurityConfig is set Android ignores usesCleartextTraffic).
// The real private-range rule is enforced in JS by src/transport/plaintext-host-policy.ts (Edit
// host). The <domain-config> below documents and pins the dev hosts and is the place to flip
// <base-config> to false if Orca ever stops needing arbitrary LAN cleartext.
function networkSecurityConfigXml() {
  const domains = [
    ...CLEARTEXT_DEV_DOMAINS.map(
      (domain) => `    <domain includeSubdomains="false">${domain}</domain>`
    ),
    ...CLEARTEXT_SUBDOMAIN_DOMAINS.map(
      (domain) => `    <domain includeSubdomains="true">${domain}</domain>`
    )
  ].join('\n')
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/android-network-security-config.js. Do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true" />
  <domain-config cleartextTrafficPermitted="true">
${domains}
  </domain-config>
</network-security-config>
`
}

module.exports = function withAndroidNetworkSecurityConfig(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml')
      await fs.promises.mkdir(dir, { recursive: true })
      await fs.promises.writeFile(
        path.join(dir, 'network_security_config.xml'),
        networkSecurityConfigXml()
      )
      return cfg
    }
  ])
  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0]
    if (application) {
      application.$['android:networkSecurityConfig'] = '@xml/network_security_config'
    }
    return cfg
  })
}

module.exports.networkSecurityConfigXml = networkSecurityConfigXml
module.exports.CLEARTEXT_DEV_DOMAINS = CLEARTEXT_DEV_DOMAINS
module.exports.CLEARTEXT_SUBDOMAIN_DOMAINS = CLEARTEXT_SUBDOMAIN_DOMAINS
